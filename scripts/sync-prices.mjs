#!/usr/bin/env node
/**
 * Writes src/lib/pricing/prices.json, the prices the site shows in each currency, from Polar: each product's price
 * per currency, less the discount its checkout link applies (the Desktop buttons take the early-adopter codes).
 *
 * Usage:
 *   POLAR_TOKEN=<read-only token> node scripts/sync-prices.mjs [--check]
 *
 * --check  Compare only. Exits 1 if the committed file is out of date.
 *
 * Fails, writing nothing, when a product lacks a price in one of the currencies, when two prices the site shows are
 * the same in US dollars but differ in another currency (the Worker swaps amounts by their dollar value), or when a
 * checkout link's discount has no amount in a currency.
 */

import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { CURRENCIES, amountMap } from '../src/lib/pricing/local-prices.js';

const REPO_ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
export const OUTPUT_PATH = join(REPO_ROOT, 'src', 'lib', 'pricing', 'prices.json');
const API = 'https://api.polar.sh';

/** What the site shows, and where in Polar each price comes from. */
const SOURCES = {
	'pro-monthly': { link: 'polar_cl_pgvSZTf2YwHmfTkRJl7ubotud3O59hKmEykhn1L3qZh' },
	'pro-annual': { link: 'polar_cl_ci0ZpYCKh1KNht5eS6xnvHYkRV7TcX1LDh13L1HGBZb' },
	'pro-lifetime': { link: 'polar_cl_Q7TCkUeGqGBmO5qfq2qaLMbtCiMXXKJtL9A014TEJw3' },
	'connect-pack-750': { product: '2be718cb-a1dd-4029-9b09-43a554a1eb2c' },
	'connect-pack-2000': { product: '78c11ecc-c70d-4c27-b716-929a0cb758e0' },
	'connect-monthly-1500': { product: '20b36c7b-64c6-46c4-a5d8-00137dfd7614' },
	'connect-monthly-7500': { product: '289025b2-d026-48ca-a899-8615f5f696b9' }
};

async function get(path) {
	const res = await fetch(`${API}${path}`, {
		headers: {
			authorization: `Bearer ${process.env.POLAR_TOKEN}`,
			accept: 'application/json',
			'user-agent': 'editmamei-web sync-prices'
		}
	});
	if (!res.ok) throw new Error(`Polar answered ${res.status} for ${path.split('?')[0]}`);
	return res.json();
}

/** A product's live fixed prices, in cents, by currency. */
function centsOf(product) {
	const out = {};
	for (const p of product.prices) {
		if (p.is_archived || p.amount_type !== 'fixed') continue;
		if (out[p.price_currency] !== undefined)
			throw new Error(`${product.name} has two live ${p.price_currency} prices`);
		out[p.price_currency] = p.price_amount;
	}
	for (const c of CURRENCIES)
		if (out[c] === undefined) throw new Error(`${product.name} has no ${c} price`);
	return out;
}

/** Cents by currency, as whole currency units. */
const units = (cents) => Object.fromEntries(CURRENCIES.map((c) => [c, cents[c] / 100]));

export async function fromPolar() {
	const links = (await get('/v1/checkout-links/?limit=100')).items;
	const cents = { free: { usd: 0, eur: 0, gbp: 0 } };
	for (const [id, src] of Object.entries(SOURCES)) {
		if (src.product) {
			cents[id] = centsOf(await get(`/v1/products/${src.product}/`));
			continue;
		}
		const link = links.find((l) => l.url?.endsWith(src.link));
		if (!link) throw new Error(`no checkout link ${src.link.slice(0, 16)}… for ${id}`);
		if (link.products.length !== 1)
			throw new Error(`checkout link for ${id} sells ${link.products.length} products`);
		const list = centsOf(await get(`/v1/products/${link.products[0].id}/`));
		const discount = link.discount_id ? await get(`/v1/discounts/${link.discount_id}/`) : null;
		if (discount && discount.type !== 'fixed')
			throw new Error(`the discount on ${id} is not a fixed amount`);
		// The site shows the discounted price as the price, so it must hold for every renewal, not the first period only.
		// A one-time payment's discount applies once by definition.
		if (discount && discount.duration !== 'forever' && link.products[0].is_recurring !== false)
			throw new Error(`the discount on ${id} lasts ${discount.duration}, not forever`);
		cents[id] = {};
		for (const c of CURRENCIES) {
			const off = discount ? discount.amounts?.[c] : 0;
			if (off === undefined) throw new Error(`the discount on ${id} has no ${c} amount`);
			cents[id][c] = list[c] - off;
		}
	}
	cents['pro-annual-saving'] = Object.fromEntries(
		CURRENCIES.map((c) => [c, 12 * cents['pro-monthly'][c] - cents['pro-annual'][c]])
	);
	const prices = Object.fromEntries(Object.entries(cents).map(([id, v]) => [id, units(v)]));
	amountMap(prices); // throws on a dollar amount that two prices share with different local amounts
	return prices;
}

export function render(prices) {
	const sorted = Object.fromEntries(
		Object.keys(prices)
			.sort()
			.map((k) => [k, prices[k]])
	);
	return `${JSON.stringify({ note: 'Generated by scripts/sync-prices.mjs from Polar. Do not edit by hand.', prices: sorted }, null, '\t')}\n`;
}

async function main() {
	if (!process.env.POLAR_TOKEN) throw new Error('set POLAR_TOKEN to a read-only Polar token');
	const next = render(await fromPolar());
	if (process.argv.includes('--check')) {
		const current = readFileSync(OUTPUT_PATH, 'utf8');
		if (current !== next) {
			console.error('src/lib/pricing/prices.json is out of date: run npm run sync:prices');
			process.exit(1);
		}
		console.log('prices.json matches Polar');
		return;
	}
	writeFileSync(OUTPUT_PATH, next);
	console.log(`wrote ${OUTPUT_PATH}`);
}

if (import.meta.url === pathToFileURL(process.argv[1] ?? '').href) {
	main().catch((error) => {
		console.error(error.message);
		process.exit(1);
	});
}
